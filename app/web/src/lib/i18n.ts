export function readStoredLang(): Lang {
  try {
    return localStorage.getItem(STORAGE_KEY) === 'zh' ? 'zh' : 'en'
  } catch {
    return 'en'
  }
}

export function storeLang(lang: Lang): void {
  try {
    localStorage.setItem(STORAGE_KEY, lang)
  } catch {
    /* storage unavailable (private mode) — language just won't persist */
  }
}

/** Translate `key` for `lang`, substituting {0}, {1} … placeholders. Falls back to English, then the key. */
export function translate(lang: Lang, key: string, ...args: (string | number)[]): string {
  let s = I18N[lang]?.[key] ?? I18N.en[key] ?? key
  args.forEach((v, i) => {
    s = s.split(`{${i}}`).join(String(v))
  })
  return s
}

/** Strip a leading emoji token (legacy `tip()`) — for labels that already sit next to a Feather icon. */
export function stripLeadingEmoji(s: string): string {
  const i = s.indexOf(' ')
  return i < 0 ? s : s.slice(i + 1)
}

export interface I18nValue {
  lang: Lang
  setLang: (lang: Lang) => void
  /** Translate `key`, substituting {0}, {1} … placeholders. */
  t: (key: string, ...args: (string | number)[]) => string
  /** Like t(), but strips a leading emoji token. */
  tip: (key: string) => string
}

export const I18nContext = createContext<I18nValue | null>(null)

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used within an I18nProvider')
  return ctx
}

export function useT() {
  return useI18n().t
}
